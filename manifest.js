lines.push('copy them if you want to keep your existing setup, leave them out for a clean install.');
lines.push('');

fs.writeFileSync(path.join(root, 'FILES.md'), lines.join('\n'));
console.log(`wrote FILES.md (${files.length} files, ${human(sourceBytes)})`);
