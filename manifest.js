function human(bytes) {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / 1048576).toFixed(1)} MB`;
}

function walk(dir, prefix = '', out = []) {
  const entries = fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name));
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    const rel = prefix ? `${prefix}${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) {
        // top-level generated folders are summarised as one row
        out.push({ rel: `${rel}/`, kind: 'runtime-dir', size: dirSize(full), files: countFiles(full), note: RUNTIME_DIRS[entry.name] || 'generated' });
        continue;
      }
      if (isHidden(entry.name)) continue;            // .cache, .pm2, .local, tooling state
      out.push({ rel: `${rel}/`, kind: 'dir', size: 0, files: 0, note: '' });
      walk(full, `${rel}/`, out);
    } else {
      if (isHidden(entry.name) && !['.env', '.env.example', '.gitignore'].includes(entry.name)) continue;
      out.push({ rel, kind: 'file', size: fs.statSync(full).size, files: 1, note: NOTE[rel] || describe(full) });
    }
  }
  return out;
}

function dirSize(dir) {
  let total = 0;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    try {
      if (entry.isDirectory()) total += dirSize(full);
      else total += fs.statSync(full).size;
    } catch (_) {}
  }
  return total;
}

function countFiles(dir) {
  let n = 0;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) n += countFiles(path.join(dir, entry.name));
    else n += 1;
  }
  return n;
}

/** First meaningful sentence of a file's own header comment - its summary. */
function describe(file) {
  if (!/\.(js|cjs|mjs|ts|sh|css|md|json|yml|html)$/.test(file)) return '';
  let text;
  try { text = fs.readFileSync(file, 'utf8').slice(0, 3000); } catch (_) { return ''; }
  text = text.replace(/^#![^\n]*\n/, '').replace(/^\s*'use strict';?\s*\n/, '').replace(/^\s*"use strict";?\s*\n/, '');
  const block = text.match(/^\s*(?:\/\*+|<\!--|#{1,6}\s)\s*([\s\S]*?)(?:\*\/|-->|\n\s*\n|$)/);
  if (!block) return '';
  const lines = block[1]
    .split('\n')
    .map((l) => l.replace(/^\s*\*?\s?/, '').replace(/^#+\s*/, '').trim())
    .filter((l) => l && !/^[-=*_]+$/.test(l));
  const line = lines.slice(0, 2).join(' ');
  const clean = line.replace(/`/g, '"').replace(/\|/g, '/').replace(/\s+/g, ' ').trim();
  if (!clean) return '';
  return clean.length > 110 ? `${clean.slice(0, 107)}…` : clean;
}

