lines.push('unzip zenith-panel.zip && cd zenith-panel');
lines.push('npm install            # dependencies + jsdom (dev)');
lines.push('npm start              # or: bash install.sh -y   (full host install)');
lines.push('npm run verify         # full verification run in a throwaway panel');
lines.push('```');
lines.push('');
